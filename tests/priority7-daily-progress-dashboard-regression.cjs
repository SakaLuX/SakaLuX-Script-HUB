'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');

const source=fs.readFileSync('SakaLuX-Suite.user.js','utf8');
const BEGIN='/* SakaLuX Suite Daily Progress Dashboard — BEGIN */';
const END='/* SakaLuX Suite Daily Progress Dashboard — END */';
const start=source.indexOf(BEGIN), end=source.indexOf(END,start);
assert.ok(start>=0&&end>start,'Daily Progress block exists');
assert.match(source,/^\/\/\s*@version\s+0\.9\.939\s*$/m,'Suite bumped to v0.9.939');
const block=source.slice(start+BEGIN.length,end);
assert.ok(block.includes('SakaLuXSuiteDailyProgress'),'public Daily Progress API exists');
assert.ok(block.includes('sakalux_suite_daily_progress_v1'),'daily progress storage exists');
assert.ok(block.includes('sakalux_suite_daily_goals_v1'),'goal template storage exists');
assert.ok(block.includes("id: 'gym'"),'Gym automatic goal exists');
assert.ok(block.includes("id: 'missions'"),'Missions automatic goal exists');
assert.ok(block.includes("id: 'prayer'"),'Prayer automatic goal exists');
assert.ok(block.includes('MAX_HISTORY = 14'),'history is bounded');
assert.ok(!/GM_xmlhttpRequest|api\.torn\.com|SakaLuXCore\?\.api\.request/.test(block),'dashboard adds no API/network requests');

(async()=>{
  const dom=new JSDOM('<!doctype html><html><head></head><body><button id="sakalux-master-suite-launcher">Suite</button></body></html>',{url:'https://www.torn.com/index.php',runScripts:'outside-only',pretendToBeVisual:true});
  const {window}=dom;
  window.confirm=()=>true;
  window.SakaLuXCore={router:{onChange(fn){this.fn=fn;return()=>{};},bind(){return true;}}};
  window.eval(block);
  await new Promise(r=>setTimeout(r,0));
  const api=window.SakaLuXSuiteDailyProgress;
  assert.ok(api,'runtime API initialized');
  assert.equal(api.version,'1.0.0');
  assert.ok(window.document.getElementById('slx-suite-daily-launcher'),'launcher mounted');
  assert.ok(window.document.getElementById('sakalux-module-bridge-daily-progress-dashboard'),'bridge mounted');
  api.open();
  assert.equal(window.document.getElementById('slx-suite-daily-progress').hidden,false,'dashboard opens');
  const before=api.snapshot();
  assert.equal(before.summary.done>=1,true,'visit goal completes automatically');
  const custom=api.addGoal('Check bazaar');
  assert.ok(custom,'custom recurring goal added');
  api.complete(custom,true);
  const after=api.snapshot();
  assert.ok(after.summary.goals>=5,'custom goal included');
  assert.ok(after.summary.done>=2,'custom completion counted');
  api.resetToday();
  const reset=api.snapshot();
  assert.equal(reset.summary.done,1,'reset retains only automatic visit completion');
  dom.window.close();
  console.log('Priority 7 Daily Progress Dashboard regression passed.');
})().catch(err=>{console.error(err);process.exitCode=1;});
