 'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const source=fs.readFileSync('SakaLuX-Market-Intelligence.user.js','utf8');
const start=source.indexOf('async function isPro()'),end=source.indexOf('function locked()',start);
assert(start>=0&&end>start,'Market exposes an independent entitlement check');
const block=source.slice(start,end);
assert.match(block,/SakaLuXLicenseClient.check\(k\)/,'Market shares the cross-realm signed cache and cooldown');
assert.match(block,/k!==key\(\)/,'A changed account rejects stale responses');
assert.match(block,/verifiedGrantExpiresAt/,'A reused certificate never extends its original lifetime');
assert.match(block,/verificationState='unavailable'/,'Failed verification remains unknown');
assert.match(block,/verifiedKey=ok\?k:''/,'Explicit FREE results clear the local grant');
assert(!source.includes('restoreRecentGrant'),'Unsigned legacy storage cannot renew PRO');
assert(source.includes("SakaLuX:MarketProReady"),'Successful standalone startup signals the UI');
console.log('Market startup, scoped grants and certificate bounds passed.');
