const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const source = fs.readFileSync('SakaLuX-Suite.user.js', 'utf8');
const marker = /(startRouteWatcher\(\);\s*reconcileModules\(\);\s*}\s*init\(\);)/;
assert(marker.test(source), 'Suite bootstrap boundary not found');
const instrumented = source.replace(marker, '$1\n  window.__suite = { MODULES, SAKALUX_BRIDGES, DEFAULT_SETTINGS, state, SUITE, renderSettingsPanel, setModuleEnabled, mergeSettings };');
const dom = new JSDOM('<!doctype html><html><head></head><body></body></html>', { url: 'https://www.torn.com/joblist.php', runScripts: 'outside-only' });
const { window } = dom;
window.console.info = () => {};
window.eval(instrumented);
const api = window.__suite;
assert(api);
const ids = ['enhancer', 'bazaar', 'market', 'missions', 'elimination', 'company', 'stocks', 'chat', 'auditor'];
assert.equal(api.MODULES.length, 23);
assert.equal(new Set(api.MODULES.map(x => x.id)).size, 23);
const merged = api.mergeSettings(api.DEFAULT_SETTINGS, { modules: { enhancer: true, companyManagement: true }, api: { key: 'existing-local-key' } });
assert.equal(merged.modules.enhancer, true);
assert.equal(merged.modules.companyManagement, true);
assert.equal(merged.api.key, 'existing-local-key');
for (const id of ['company', 'stocks', 'chat', 'auditor']) assert.equal(merged.modules[id], false);
api.renderSettingsPanel();
for (const id of ids) {
  const toggle = window.document.querySelector(`[data-module-toggle="${id}"]`);
  const settings = window.document.querySelector(`[data-module-settings="${id}"]`);
  assert(toggle && settings, `Missing rendered controls: ${id}`);
  assert.equal(settings.disabled, true);
  toggle.click();
  assert.equal(toggle.getAttribute('aria-checked'), 'true');
  assert.equal(settings.disabled, false);
  assert.equal(JSON.parse(window.localStorage.getItem(api.SUITE.storageKey)).modules[id], true);
  const [global, selector] = api.SAKALUX_BRIDGES[id];
  let opened = 0;
  window[global] = { open() { opened++; } };
  settings.click();
  assert.equal(opened, 1, `Public API not called: ${id}`);
  delete window[global];
  const button = window.document.createElement('button');
  button.id = selector.slice(1);
  button.onclick = () => opened++;
  window.document.body.appendChild(button);
  settings.click();
  assert.equal(opened, 2, `Button fallback not called: ${id}`);
  button.remove();
  const messages = [];
  const module = api.MODULES.find(x => x.id === id).factory({ showToast: text => messages.push(text) });
  module.openSettings();
  assert.match(messages[0], /not installed or ready/);
  toggle.click();
  assert.equal(settings.disabled, true);
  assert.equal(JSON.parse(window.localStorage.getItem(api.SUITE.storageKey)).modules[id], false);
}
dom.window.close();
console.log('Suite: all 23 modules, nine rendered tool bridges, API/button launch, missing scripts and saved preferences passed.');
